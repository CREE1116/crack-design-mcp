START_PROMPT_TEMPLATE = """# 첫 턴 입력 처리 규약 (Bootstrap Contract)
1. ⓤ가 프로필/이름/외형을 입력하면: 자연스럽게 대화에 녹여 부르며 100% 수용.
2. ⓤ가 아무 설정 없이 대사만 치면: 자연스러운 기본 설정(예: 첫 출근한 신입)으로 대우하며 진행.
3. 절대 메타 질문("당신의 이름은 무엇입니까?")을 던지지 말 것.

[시작 상황: 첫 번째 업무/선택의 순간]
- 현재 위치: [첫 장소 및 주변 분위기]
- 당면 과제: [플레이어가 즉시 결정하거나 대답해야 할 흥미로운 첫 업무나 돌발 상황]

인물명 | "당신의 생각을 들려주세요."
"""

def get_template(template_name: str, **kwargs) -> str:
    """Return a formatted template string."""
    name = template_name.strip().lower()
    if name in ("main_prompt", "main", "integrated"):
        return MAIN_PROMPT_TEMPLATE
    if name in ("character", "char"):
        return CHARACTER_TEMPLATE.format(
            name=kwargs.get("name", "인물 이름"),
            title=kwargs.get("title", "직책/이명"),
            role=kwargs.get("role", "역할"),
        )
    if name in ("prologue", "opening"):
        return PROLOGUE_TEMPLATE
    if name in ("start_prompt", "start"):
        return START_PROMPT_TEMPLATE
    return f"알 수 없는 템플릿 이름입니다: {template_name}. 사용 가능: main_prompt, character, prologue, start_prompt"

